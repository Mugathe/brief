const CATALOG: Record<Lang, Messages> = { en, sw, fr, es, pt, ar, hi };

/** Looks up a message in a language and fills in {placeholders}. */
export function t(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  const text = CATALOG[lang]?.[key] ?? en[key];
  return vars ? text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : text;
}

/** A category name in the reader's language. Unknown names (from outlets' own sections) are shown as they are. */
export const categoryLabel = (lang: Lang, category: string): string => {
  const key = `cat.${category}` as Key;
  return key in en ? t(lang, key) : category;
};

const regionNames = new Map<string, Intl.DisplayNames>();
function regionName(lang: Lang, iso: string): string {
  let names = regionNames.get(lang);
  if (!names) { names = new Intl.DisplayNames([dateLocale(lang)], { type: "region" }); regionNames.set(lang, names); }
  return names.of(iso) ?? iso;
}

/** "in Kenya" in each language, with the right preposition and article ("au Kenya", "nchini Kenya", "no Quênia"). */
const WHERE_FR: Record<string, string> = { KE: "au Kenya", UG: "en Ouganda", TZ: "en Tanzanie", NG: "au Nigeria", GH: "au Ghana", ZA: "en Afrique du Sud", SN: "au Sénégal", CI: "en Côte d’Ivoire", GB: "au Royaume-Uni", US: "aux États-Unis", IN: "en Inde", AU: "en Australie", CA: "au Canada", FR: "en France", ES: "en Espagne", MX: "au Mexique", BR: "au Brésil" };
const WHERE_PT: Record<string, string> = { KE: "no Quênia", UG: "em Uganda", TZ: "na Tanzânia", NG: "na Nigéria", GH: "em Gana", ZA: "na África do Sul", SN: "no Senegal", CI: "na Costa do Marfim", GB: "no Reino Unido", US: "nos Estados Unidos", IN: "na Índia", AU: "na Austrália", CA: "no Canadá", FR: "na França", ES: "na Espanha", MX: "no México", BR: "no Brasil" };

/** Where something happens: "in the world", "in Kenya", "au Kenya", "nchini Kenya", "en Kenia", "no Quênia". */
export function inPlace(edition: Edition, lang: Lang): string {
  const world = edition.code === WORLD || !edition.iso;
  const name = world ? "" : regionName(lang, edition.iso!);
  switch (lang) {
    case "en": return world ? "in the world" : `in ${edition.place}`;
    case "sw": return world ? "duniani" : `nchini ${name}`;
    case "fr": return world ? "dans le monde" : (WHERE_FR[edition.iso!] ?? `en ${name}`);
    case "es": return world ? "en el mundo" : `en ${name}`;
    case "pt": return world ? "no mundo" : (WHERE_PT[edition.iso!] ?? `em ${name}`);
    case "ar": return world ? "في العالم" : `في ${name}`;
    case "hi": return world ? "दुनिया भर में" : `${name} में`;
  }
}

const WORLD_NAME: Record<Lang, string> = { en: "The World", sw: "Dunia", fr: "Le monde", es: "El mundo", pt: "O mundo", ar: "العالم", hi: "दुनिया" };

/** An edition's place name in the reader's language: "Kenya", "Kenia", "Le monde". */
export function placeName(edition: Edition, lang: Lang): string {
  return edition.code === WORLD || !edition.iso ? (lang === "en" ? "the world" : t(lang, "common.world")) : regionName(lang, edition.iso);
}

/** The edition picker label: flag and name in the reader's language, with the language for second-language editions. */
export function editionLabel(edition: Edition, lang: Lang): string {
  if (edition.code === WORLD) return `${edition.flag} ${WORLD_NAME[lang]}`;
  const base = regionName(lang, edition.iso ?? edition.code);
  return `${edition.flag} ${edition.code.includes("-") ? `${base} · ${LANGS.find((l) => l.code === edition.lang)?.name}` : base}`;
}

const BULLETIN: Record<Lang, (place: string) => string> = {
  en: (p) => `${p} in a Nutshell`, sw: (p) => `${p} kwa Ufupi`, fr: (p) => `${p} en bref`, es: (p) => `${p} en breve`, pt: (p) => `${p} em resumo`,
  ar: (p) => `${p} باختصار`, hi: (p) => `${p} संक्षेप में`,
};

/** The name of the spoken bulletin for an edition, in the language it is read in. */
export function bulletinTitle(edition: Edition, lang: Lang): string {
  const place = edition.code === WORLD || !edition.iso ? WORLD_NAME[lang] : regionName(lang, edition.iso);
  return BULLETIN[lang](place);
}

/** The bulletin name split for the page heading: the plain part, and the part shown in the accent colour. */
export function bulletinParts(edition: Edition, lang: Lang): { lead: string; accent: string } {
  const title = bulletinTitle(edition, lang);
  if (lang === "hi") return { lead: title.replace(/ संक्षेप में$/, ""), accent: "संक्षेप में" };
  const i = title.lastIndexOf(" ");
  return i < 0 ? { lead: "", accent: title } : { lead: title.slice(0, i), accent: title.slice(i + 1) };
}
